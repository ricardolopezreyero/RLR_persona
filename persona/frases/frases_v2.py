def main():
    aqui = os.path.dirname(os.path.abspath(__file__))
    frases, vistos = [], set()
    for tema, bloque in T.items():
        for f in [x.strip() for x in bloque.strip().split('\n') if x.strip()]:
            assert f not in vistos, f
            vistos.add(f); frases.append((tema, f))
    n = len(frases)
    sello = datetime.datetime.now().strftime('%Y-%m-%d %Hh%M')
    nombre = f'{n} frases · Ricardo López Reyero · RLR · v2 · {sello}.txt'
    plano = '\n'.join(f'{i}, {f[:-1] if f.endswith(".") else f}, RLR' for i, (_, f) in enumerate(frases, 1)) + '\n'
    open(os.path.join(aqui, 'frases_v2.txt'), 'w').write(plano)
    md = ['# Frases de Ricardo López Reyero · versión 2', '']
    i = 0
    for tema in T:
        md += [f'## {tema}', '']
        for t, f in frases:
            if t == tema:
                i += 1; md.append(f'{i}. {f}')
        md.append('')
    open(os.path.join(aqui, 'frases_v2.md'), 'w').write('\n'.join(md))
    for d in ('~/Downloads', '~/Desktop/HTML'):
        shutil.copy(os.path.join(aqui, 'frases_v2.txt'), os.path.join(os.path.expanduser(d), nombre))
    print(n, nombre, {t: sum(1 for x, _ in frases if x == t) for t in T})


if __name__ == '__main__':
    main()
